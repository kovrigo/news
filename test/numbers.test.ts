import { describe, expect, test } from 'bun:test';
import { extractNumbers } from '../src/core/numbers.ts';

const table: Array<[string, number[]]> = [
  ['сорок миллионов', [40e6]],
  ['40 млн', [40e6]],
  ['40 000 000', [40e6]],
  ['1,5 млрд', [1.5e9]],
  ['полтора миллиона', [1.5e6]],
  ['полторы тысячи', [1500]],
  ['полутора миллиарда', [1.5e9]],
  ['двухсот тысяч', [200e3]],
  ['двадцать шестом', []],
  ['в двадцать шестом году', []],
  ['40 000', [40000]],
  ['40 000 рублей', [40000]],
  ['40 000', [40000]],
  ['1,5', [1.5]],
  ['0,3 млн', [300000]],
  ['12 тыс.', [12000]],
  ['12 тысяч человек', [12000]],
  ['сто двадцать человек', [120]],
  ['сорока лет', [40]],
  ['девятьсот девяносто девять', [999]],
  ['тремстам рублям', [300]],
  ['три тысячи двадцать пять', [3025]],
  ['два миллиона триста тысяч', [2.3e6]],
  ['2 млн 300 тыс. рублей', [2.3e6]],
  ['тысяча человек', [1000]],
  ['несколько тысяч человек', []],
  ['90 дней и 48 млн рублей', [90, 48e6]],
  ['в 2024 году 300 человек', [2024, 300]],
  ['пять десять', [5, 10]],
  ['ноль', [0]],
  ['сто пятый километр', []],
  ['40%', [40]],
  ['Мост закрыт', []],
  ['', []],
];

describe('extractNumbers table', () => {
  for (const [input, expected] of table) test(JSON.stringify(input), () => expect(extractNumbers(input)).toEqual(expected));
});

test('words and digits give the same number', () => {
  expect(extractNumbers('сорок миллионов')).toEqual(extractNumbers('40 000 000'));
});
